const std = @import("std");
const Io = std.Io;

/// One shipped asset: `src` is the repo path (the single source of truth) and
/// `dest` is the path relative to the install target.
const Asset = struct { src: []const u8, dest: []const u8 };

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});
    const version = b.option([]const u8, "version", "Version string") orelse "0.1.0-dev";

    const options = b.addOptions();
    options.addOption([]const u8, "version", version);

    const root_module = b.createModule(.{
        .root_source_file = b.path("src/main.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
    });
    root_module.addOptions("build_options", options);
    embedAssets(b, root_module);
    root_module.addIncludePath(b.path("vendor/sqlite"));
    root_module.addCSourceFile(.{
        .file = b.path("vendor/sqlite/sqlite3.c"),
        .flags = &.{
            "-std=c99",
            "-DSQLITE_THREADSAFE=0", // single-threaded entry points only; see vendor/sqlite/PIN.md
            "-DSQLITE_OMIT_LOAD_EXTENSION",
            "-DSQLITE_DQS=0",
            "-DSQLITE_DEFAULT_FOREIGN_KEYS=1",
            "-DSQLITE_DEFAULT_WAL_SYNCHRONOUS=1",
            "-DSQLITE_ENABLE_FTS5", // knowledge_fts; see vendor/sqlite/PIN.md
        },
    });

    const exe = b.addExecutable(.{
        .name = "ztd",
        .root_module = root_module,
    });
    b.installArtifact(exe);

    const run_cmd = b.addRunArtifact(exe);
    run_cmd.step.dependOn(b.getInstallStep());
    run_cmd.addPassthruArgs();
    const run_step = b.step("run", "Run ztd");
    run_step.dependOn(&run_cmd.step);

    const tests = b.addTest(.{ .root_module = exe.root_module });
    const run_tests = b.addRunArtifact(tests);
    const test_step = b.step("test", "Run tests");
    test_step.dependOn(&run_tests.step);
}

/// Embeds the shipped bundles as a generated `assets.zig` manifest imported
/// as `assets`: every entry lists its install-relative path and the bytes of
/// the repo file it was copied from, so the repo stays the single source of
/// truth and no copy lands in the tree. The expected counts are part of the
/// contract — adding or removing an asset must update them here and in the
/// manifest test. Nothing outside skills/, commands/ and method/templates is
/// embedded.
fn embedAssets(b: *std.Build, root_module: *std.Build.Module) void {
    const io = b.graph.io;
    const arena = b.graph.arena;

    var opencode: std.ArrayList(Asset) = .empty;
    defer opencode.deinit(arena);
    for ([_][]const u8{
        "integrations/opencode/skills",
        "integrations/opencode/commands",
    }) |dir| {
        walk(b, io, arena, &opencode, dir, dir["integrations/opencode/".len..]);
    }
    var templates: std.ArrayList(Asset) = .empty;
    defer templates.deinit(arena);
    walk(b, io, arena, &templates, "method/templates", "templates");

    byDest(opencode.items);
    byDest(templates.items);

    var skills: usize = 0;
    var commands: usize = 0;
    for (opencode.items) |a| {
        if (std.mem.startsWith(u8, a.src, "integrations/opencode/skills/")) skills += 1 //
        else if (std.mem.startsWith(u8, a.src, "integrations/opencode/commands/")) commands += 1 //
        else @panic(b.fmt("ztd: unexpected embedded asset {s}", .{a.src}));
    }
    if (skills != 10) @panic(b.fmt("ztd: expected 10 skills, found {d}", .{skills}));
    if (commands != 13) @panic(b.fmt("ztd: expected 13 commands, found {d}", .{commands}));
    if (templates.items.len != 6) @panic(b.fmt("ztd: expected 6 templates, found {d}", .{templates.items.len}));
    for (templates.items) |a| {
        if (!std.mem.startsWith(u8, a.src, "method/templates/")) @panic(b.fmt("ztd: unexpected embedded template {s}", .{a.src}));
    }

    const wf = b.addWriteFiles();
    var text: std.ArrayList(u8) = .empty;
    defer text.deinit(arena);
    append(arena, &text,
        \\//! Generated by build.zig from integrations/opencode and method/templates.
        \\//! Do not edit: the repo files are the source of truth.
        \\pub const Entry = struct { path: []const u8, data: []const u8 };
        \\
        \\/// Skills and commands published under $HOME/.config/opencode.
        \\pub const opencode = [_]Entry{
        \\
    );
    for (opencode.items) |a| {
        checkPath(b, a);
        _ = wf.addCopyFile(b.path(a.src), b.fmt("data/{s}", .{a.src}));
        appendFmt(arena, &text, "    .{{ .path = \"{s}\", .data = @embedFile(\"data/{s}\") }},\n", .{ a.dest, a.src });
    }
    append(arena, &text, "};\n");
    append(arena, &text,
        \\
        \\/// Method templates seeded into <store>/templates by `ztd init`.
        \\pub const templates = [_]Entry{
        \\
    );
    for (templates.items) |a| {
        checkPath(b, a);
        _ = wf.addCopyFile(b.path(a.src), b.fmt("data/{s}", .{a.src}));
        appendFmt(arena, &text, "    .{{ .path = \"{s}\", .data = @embedFile(\"data/{s}\") }},\n", .{ a.dest, a.src });
    }
    append(arena, &text, "};\n");

    const manifest = wf.add("assets.zig", text.items);
    root_module.addAnonymousImport("assets", .{ .root_source_file = manifest });
}

/// Asset paths end up inside string literals in the generated source: only
/// plain path bytes may appear there.
fn checkPath(b: *std.Build, asset: Asset) void {
    for ([_][]const u8{ asset.src, asset.dest }) |path| {
        for (path) |c| {
            const ok = (c >= 'a' and c <= 'z') or (c >= 'A' and c <= 'Z') or
                (c >= '0' and c <= '9') or c == '/' or c == '.' or c == '_' or c == '-';
            if (!ok) @panic(b.fmt("ztd: unsafe asset path {s}", .{asset.src}));
        }
    }
}

/// Recursively collects regular files. A traversal error fails the build
/// instead of silently shipping a partial bundle.
fn walk(b: *std.Build, io: std.Io, arena: std.mem.Allocator, out: *std.ArrayList(Asset), src_dir: []const u8, dest_prefix: []const u8) void {
    var dir = Io.Dir.cwd().openDir(io, src_dir, .{ .iterate = true }) catch |err|
        @panic(b.fmt("ztd: cannot open {s}: {s}", .{ src_dir, @errorName(err) }));
    defer dir.close(io);
    var it = dir.iterate();
    while (it.next(io) catch |err| @panic(b.fmt("ztd: cannot walk {s}: {s}", .{ src_dir, @errorName(err) }))) |entry| {
        const src = b.fmt("{s}/{s}", .{ src_dir, entry.name });
        const dest = b.fmt("{s}/{s}", .{ dest_prefix, entry.name });
        var kind = entry.kind;
        if (kind == .unknown) {
            // Some filesystems do not report the type in the directory entry.
            kind = (dir.statFile(io, entry.name, .{}) catch |err|
                @panic(b.fmt("ztd: cannot stat {s}: {s}", .{ src, @errorName(err) }))).kind;
        }
        switch (kind) {
            .directory => walk(b, io, arena, out, src, dest),
            .file => out.append(arena, .{ .src = src, .dest = dest }) catch @panic("ztd: out of memory"),
            else => @panic(b.fmt("ztd: non-regular asset {s}", .{src})),
        }
    }
}

fn byDest(items: []Asset) void {
    std.mem.sort(Asset, items, {}, struct {
        fn lt(_: void, lhs: Asset, rhs: Asset) bool {
            return std.mem.lessThan(u8, lhs.dest, rhs.dest);
        }
    }.lt);
}

fn append(arena: std.mem.Allocator, list: *std.ArrayList(u8), bytes: []const u8) void {
    list.appendSlice(arena, bytes) catch @panic("ztd: out of memory");
}

fn appendFmt(arena: std.mem.Allocator, list: *std.ArrayList(u8), comptime fmt: []const u8, args: anytype) void {
    const line = std.fmt.allocPrint(arena, fmt, args) catch @panic("ztd: out of memory");
    list.appendSlice(arena, line) catch @panic("ztd: out of memory");
}
