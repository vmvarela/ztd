#!/usr/bin/env python3
"""Embed the `ztd install` bundles into src/install_bundle/ and list them.

Zig only lets a module @embedFile files under its own root (src/), so the
bundles are copied there and src/install_assets.zig is generated from the copy.
`zig build test` compares the copy with the originals and fails when stale, so
run this after touching integrations/opencode or method/templates:

    python3 scripts/embed-install-assets.py
"""

import pathlib
import shutil

ROOT = pathlib.Path(__file__).resolve().parent.parent
# (prefix published by the installer, source tree, name under src/install_bundle)
# Only the published subtrees: the Go embed directive shipped
# integrations/opencode/skills and method/templates/*.md, and a README left
# loose in either tree must not land in $HOME/.config/opencode or the store.
BUNDLES = [
    ("integrations/opencode", ROOT / "integrations/opencode", "opencode", "skills"),
    ("method", ROOT / "method", "templates", "templates"),
]
SKIP = {".DS_Store"}


def main() -> None:
    dest_root = ROOT / "src/install_bundle"
    if dest_root.exists():
        shutil.rmtree(dest_root)
    rows = []
    for prefix, base, name, sub in BUNDLES:
        for path in sorted(p for p in (base / sub).rglob("*") if p.is_file()):
            if path.name in SKIP:
                continue
            rel = path.relative_to(base).as_posix()
            target = dest_root / name / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
            rows.append((prefix, rel, "install_bundle/" + name + "/" + rel))
    lines = [
        "// Generated by scripts/embed-install-assets.py; do not edit.",
        "// The bytes live in src/install_bundle/ because @embedFile cannot reach",
        "// outside the module root; `zig build test` fails when the copy is stale.",
        "",
        "pub const Asset = struct { prefix: []const u8, rel: []const u8, data: []const u8 };",
        "",
        "pub const assets = [_]Asset{",
    ]
    for prefix, rel, embed in rows:
        lines.append(
            '    .{ .prefix = "%s", .rel = "%s", .data = @embedFile("%s") },' % (prefix, rel, embed)
        )
    lines += ["};", ""]
    (ROOT / "src/install_assets.zig").write_text("\n".join(lines))
    print("embedded %d assets" % len(rows))


if __name__ == "__main__":
    main()
