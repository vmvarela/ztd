#!/usr/bin/env python3
"""Print the ztd CLI and MCP surface as Markdown (see docs/benchmarks/matrix.md)."""
import argparse, json, os, shutil, subprocess, sys, tempfile, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GO = "/opt/homebrew/bin/go"  # the goenv shim on PATH prints "No tests found"

def die(msg):
    print("matrix: " + msg, file=sys.stderr)
    sys.exit(1)

def resolve_binary(tmp):
    path = os.environ.get("ZTD_GO")
    if path:
        if not (os.path.isfile(path) and os.access(path, os.X_OK)):
            die("ZTD_GO is not an executable: " + path)
        return path
    if not os.path.isfile(GO):
        die("missing " + GO + "; set ZTD_GO to a built ztd binary")
    out = os.path.join(tmp, "ztd")
    cmd = [GO, "build", "-trimpath", "-ldflags=-s -w", "-o", out, "./cmd/ztd"]
    if subprocess.run(cmd, cwd=ROOT).returncode != 0:
        die("go build failed")
    return out

def split_entry(text):
    # one help line can hold several commands separated by " | ", but a " | "
    # inside a flag list (e.g. [--all | --scope S]) is not a separator
    segments, start, i = [], 0, 0
    while i < len(text):
        if text.startswith(" | ", i) and text[i + 3:i + 4].isalpha():
            segments.append(text[start:i])
            start = i + 3
        i += 1
    segments.append(text[start:])
    for segment in segments:
        cmd, flags = [], []
        words = segment.split()
        for i, word in enumerate(words):
            if word.startswith(("-", "[", "(")) or word == "|":
                flags = words[i:]
                break
            cmd.append(word)
        yield " ".join(cmd), " ".join(flags)

def cli_rows(help_text):
    rows, current, started = [], None, False
    for line in help_text.splitlines():
        if not started and not (line.startswith("  ") and line.strip()):
            continue
        started = True
        if not line.strip():
            continue
        indent = len(line) - len(line.lstrip())
        if indent < 2 or line.strip().startswith("Scope binding"):
            break  # end of the usage block
        if indent == 2:  # a new entry starts; deeper indents continue it
            if current:
                rows.extend(split_entry(" ".join(current)))
            current = [line.strip()]
        else:
            current = (current or []) + [line.strip()]
    if current:
        rows.extend(split_entry(" ".join(current)))
    return [r for r in rows if r[0]]

def mcp_tools(binpath, db, extra):
    payload = "\n".join([
        '{"jsonrpc":"2.0","id":1,"method":"initialize","params":'
        '{"protocolVersion":"2025-06-18","capabilities":{},'
        '"clientInfo":{"name":"matrix"}}}',
        '{"jsonrpc":"2.0","method":"notifications/initialized"}',
        '{"jsonrpc":"2.0","id":2,"method":"tools/list"}']) + "\n"
    proc = subprocess.Popen([binpath, "--db", db, "mcp"] + extra,
                             stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                             stderr=subprocess.PIPE, text=True)
    proc.stdin.write(payload)
    proc.stdin.flush()
    time.sleep(1)  # the server drops pending output on immediate EOF
    proc.stdin.close()
    out = proc.stdout.read()
    try:
        proc.wait(timeout=30)
    except subprocess.TimeoutExpired:
        proc.kill()
        die("mcp did not exit")
    for line in out.splitlines():
        try:
            obj = json.loads(line)
        except ValueError:
            continue
        if isinstance(obj, dict) and obj.get("id") == 2 \
                and isinstance(obj.get("result"), dict):
            return obj["result"].get("tools") or []
    die("cannot parse tools/list response (stderr: " +
        (proc.stderr.read().strip() or "empty") + ")")

def render(rows, default, opted, opt_in, schema_bytes):
    tools = {t["name"]: t for t in default}
    tools.update({t["name"]: t for t in opted})
    out = ["# ZTD CLI and MCP surface", "",
           "Generated by `scripts/matrix.py` — do not edit by hand. "
           "Regenerate from the repository root with:", "", "```sh",
           "python3 scripts/matrix.py --write", "```", "", "## CLI", "",
           "| command | flags |", "|---|---|"]
    out += ["| %s | %s |" % (c.replace("|", "\\|"), f.replace("|", "\\|"))
            for c, f in rows]
    out += ["", "## MCP tools", "",
            "| tool | requires --allow-delete-source | input properties "
            "| outputSchema |", "|---|---|---|---|"]
    for name in sorted(tools):
        tool = tools[name]
        props = list((tool.get("inputSchema") or {}).get("properties") or [])
        out.append("| %s | %s | %s | %s |" % (
            name, "yes" if name in opt_in else "no", ", ".join(props),
            "yes" if tool.get("outputSchema") else "no"))
    out += ["", "## Counts", "",
            "Commands: %d · MCP tools (default): %d · opt-in tools: %d · "
            "default tools/list schema bytes: %d" %
            (len(rows), len(default), len(opt_in), schema_bytes), ""]
    return "\n".join(out)

def main():
    ap = argparse.ArgumentParser(description="ztd CLI/MCP surface matrix")
    ap.add_argument("--write", action="store_true",
                    help="also write docs/benchmarks/matrix.md")
    args = ap.parse_args()
    tmp = tempfile.mkdtemp(prefix="ztd-matrix-")
    try:
        binpath = resolve_binary(tmp)
        db = os.path.join(tmp, "db.sqlite")
        init = subprocess.run(
            [binpath, "--db", db, "init", "--non-interactive",
             "--scope", "id=personal,kind=personal,name=Personal"],
            cwd=ROOT, capture_output=True, text=True)
        if init.returncode != 0:
            die("init failed (%d): %s" % (init.returncode,
                                         (init.stderr or init.stdout).strip()))
        help_text = subprocess.run([binpath, "--help"], cwd=ROOT,
                                   capture_output=True, text=True)
        if help_text.returncode != 0:
            die("--help failed")
        rows = cli_rows(help_text.stdout)
        default = mcp_tools(binpath, db, [])
        opted = mcp_tools(binpath, db, ["--allow-delete-source"])
        schema_bytes = len(json.dumps(default).encode("utf-8"))
        names = {t["name"] for t in default}
        opt_in = {t["name"] for t in opted} - names
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    text = render(rows, default, opted, opt_in, schema_bytes)
    print(text, end="")
    if args.write:
        with open(os.path.join(ROOT, "docs", "benchmarks", "matrix.md"), "w",
                  encoding="utf-8") as fh:
            fh.write(text)
        print("matrix: wrote docs/benchmarks/matrix.md", file=sys.stderr)

if __name__ == "__main__":
    main()
